export const copy = { mn, en };
export type PublicCopy = typeof mn;

/** The shared ticket dictionary plus the labels for event kinds, formats and states that only the database knows about. */
export type TicketDict = Dict["ticket"] & { statuses: Record<string, string> };
export function ticketDict(lang: Locale, base: Dict["ticket"]): TicketDict {
  const c = copy[lang].ticket;
  return { ...base, kinds: { ...base.kinds, ...c.kinds }, modes: { ...base.modes, ...c.modes }, statuses: c.statuses };
}

/** 1st, 2nd, 3rd… (English) · 1-р, 2-р… (Mongolian). */
export function ordinal(lang: Locale, n: number): string {
  if (lang === "mn") return `${n}-р`;
  const teen = n % 100 >= 11 && n % 100 <= 13;
  const suffix = teen ? "th" : (["th", "st", "nd", "rd"][n % 10] ?? "th");
  return `${n}${suffix}`;
}
